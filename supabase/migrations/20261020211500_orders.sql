create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  idempotency_key uuid not null unique,
  customer_name text not null,
  customer_phone text not null,
  fulfillment text not null check (fulfillment in ('delivery', 'pickup')),
  delivery_address text,
  payment_method text not null check (payment_method in ('cash_delivery', 'onsite')),
  status text not null default 'new'
    check (status in ('new', 'accepted', 'preparing', 'ready', 'completed', 'cancelled')),
  subtotal numeric(10, 2) not null check (subtotal >= 0),
  delivery_cost numeric(10, 2) not null default 0 check (delivery_cost >= 0),
  total numeric(10, 2) not null check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (fulfillment = 'delivery' and delivery_address is not null and payment_method = 'cash_delivery')
    or (fulfillment = 'pickup' and delivery_address is null and payment_method = 'onsite')
  )
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  dish_name text not null,
  category text not null,
  station text not null check (station in ('kitchen', 'bar')),
  quantity integer not null check (quantity between 1 and 99),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  line_total numeric(10, 2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  unique (order_id, dish_name)
);

create table public.staff_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.staff_members enable row level security;

grant select, update (status) on public.orders to authenticated;
grant select on public.order_items to authenticated;
grant select on public.staff_members to authenticated;

create policy "Staff can read orders"
  on public.orders for select to authenticated
  using (exists (select 1 from public.staff_members where user_id = auth.uid()));
create policy "Staff can update order status"
  on public.orders for update to authenticated
  using (exists (select 1 from public.staff_members where user_id = auth.uid()))
  with check (exists (select 1 from public.staff_members where user_id = auth.uid()));
create policy "Staff can read order items"
  on public.order_items for select to authenticated
  using (exists (select 1 from public.staff_members where user_id = auth.uid()));
create policy "Staff can read own membership"
  on public.staff_members for select to authenticated using (user_id = auth.uid());

create or replace function public.set_order_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_orders_updated_at
  before update on public.orders
  for each row execute function public.set_order_updated_at();

create or replace function public.create_web_order(p_order jsonb, p_items jsonb)
returns table (id uuid, order_number bigint, total numeric(10, 2))
language plpgsql
security definer
set search_path = public
as $$
declare
  created_order_id uuid;
  created_order_number bigint;
  created_order_total numeric(10, 2);
  existing_order public.orders%rowtype;
begin
  select * into existing_order
  from public.orders
  where idempotency_key = (p_order->>'idempotency_key')::uuid;

  if found then
    return query select existing_order.id, existing_order.order_number, existing_order.total;
    return;
  end if;

  insert into public.orders (
    idempotency_key,
    customer_name,
    customer_phone,
    fulfillment,
    delivery_address,
    payment_method,
    subtotal,
    delivery_cost,
    total
  ) values (
    (p_order->>'idempotency_key')::uuid,
    p_order->>'customer_name',
    p_order->>'customer_phone',
    p_order->>'fulfillment',
    nullif(p_order->>'delivery_address', ''),
    p_order->>'payment_method',
    (p_order->>'subtotal')::numeric,
    (p_order->>'delivery_cost')::numeric,
    (p_order->>'total')::numeric
  )
  on conflict (idempotency_key) do nothing
  returning orders.id, orders.order_number, orders.total
    into created_order_id, created_order_number, created_order_total;

  if created_order_id is null then
    select * into existing_order
    from public.orders
    where idempotency_key = (p_order->>'idempotency_key')::uuid;
    return query select existing_order.id, existing_order.order_number, existing_order.total;
    return;
  end if;

  insert into public.order_items (
    order_id, dish_name, category, station, quantity, unit_price, line_total
  )
  select
    created_order_id,
    item->>'dish_name',
    item->>'category',
    item->>'station',
    (item->>'quantity')::integer,
    (item->>'unit_price')::numeric,
    (item->>'line_total')::numeric
  from jsonb_array_elements(p_items) as item;

  return query select created_order_id, created_order_number, created_order_total;
end;
$$;

revoke all on function public.create_web_order(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.create_web_order(jsonb, jsonb) to service_role;

